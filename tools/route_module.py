#!/usr/bin/env python3
"""Write js/data/route.js from the simulator's timeline (route.json).

Usage (from klt-tracker/):
    python3 tools/route_module.py assets/clips/chinatown.route.json js/data/route.js
"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
r = json.load(open(src))
chapters = {c["index"]: [c["start"], c["end"]] for c in r["chapters"]}
with open(out, "w") as fh:
    fh.write("// GENERATED by tools/route_module.py from " + src + " -- do not edit by hand.\n")
    fh.write("// Frame ranges and key moments of the recorded simulator journey.\n")
    fh.write(f"export const ROUTE = {json.dumps({'clip': r['clip'], 'fps': r['fps'], 'frameCount': r['frameCount'], 'from': r['route']['from'], 'to': r['route']['to'], 'chapters': chapters, 'keys': r['keys'], 'attribution': r['attribution']}, indent=2)};\n")
print("wrote", out)
